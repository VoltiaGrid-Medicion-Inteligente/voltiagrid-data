import argparse
import csv
import json
import re
from collections import Counter
from pathlib import Path

DEV_SUBSET_FILE = Path("data/reference/dev_subset.json")
DOC_FILE = Path("docs/data/dev-subset.md")
MIN_SHARE = 0.01          
MIN_HOUSEHOLDS = 200      
TARGET_PER_BLOCK = 50     

def block_number(name: str) -> int:
    match = re.search(r"block_(\d+)", name)
    return int(match.group(1)) if match else -1


def read_households(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def required_items(households: list[dict], min_share: float = MIN_SHARE) -> set[tuple[str, str]]:
    total = len(households)
    groups = Counter(h["Acorn_grouped"] for h in households)
    items = {("acorn_grouped", g) for g, n in groups.items() if n / total >= min_share}
    items |= {("tariff", h["stdorToU"]) for h in households}
    return items


def _shares(rows: list[dict], column: str) -> Counter:
    counts = Counter(h[column] for h in rows)
    total = sum(counts.values()) or 1
    return Counter({k: v / total for k, v in counts.items()})


def distance(full: list[dict], subset: list[dict]) -> float:
    total = 0.0
    for column in ("Acorn_grouped", "stdorToU"):
        a, b = _shares(full, column), _shares(subset, column)
        total += sum(abs(a[k] - b[k]) for k in set(a) | set(b))
    return total


def choose_blocks(
    households: list[dict],
    min_share: float = MIN_SHARE,
    min_households: int = MIN_HOUSEHOLDS,
) -> list[str]:
    by_block: dict[str, list[dict]] = {}
    for h in households:
        by_block.setdefault(h["file"], []).append(h)

    def items_of(rows: list[dict]) -> set[tuple[str, str]]:
        return {("acorn_grouped", h["Acorn_grouped"]) for h in rows} | {("tariff", h["stdorToU"]) for h in rows}

    required = required_items(households, min_share)
    relevant_groups = {value for kind, value in required if kind == "acorn_grouped"}
    eligible = [b for b, rows in by_block.items() if any(h["Acorn_grouped"] in relevant_groups for h in rows)]
    chosen: list[str] = []
    subset: list[dict] = []
    while len(chosen) < len(eligible):
        missing = required - items_of(subset)
        if len(subset) >= min_households and not missing:
            break
        candidates = [b for b in eligible if b not in chosen]
        if len(subset) >= min_households:
            candidates = [b for b in candidates if items_of(by_block[b]) & missing] or candidates
        best = min(
            candidates,
            key=lambda b: (
                round(distance(households, subset + by_block[b]), 9),
                abs(len(by_block[b]) - TARGET_PER_BLOCK),
                block_number(b),
            ),
        )
        chosen.append(best)
        subset += by_block[best]
    return sorted(chosen, key=block_number)


def load_dev_blocks(path: Path = DEV_SUBSET_FILE) -> list[str]:
    return json.loads(path.read_text(encoding="utf-8"))["blocks"]


def select_files(paths: list[Path], blocks: list[str]) -> list[Path]:
    wanted = set(blocks)
    selected = [p for p in paths if p.stem in wanted]
    missing = wanted - {p.stem for p in selected}
    if missing:
        raise FileNotFoundError(f"dev subset blocks not found in data/raw: {sorted(missing, key=block_number)}")
    return selected

def share_table(households: list[dict], subset: list[dict], column: str) -> list[str]:
    full, part = Counter(h[column] for h in households), Counter(h[column] for h in subset)
    lines = [f"| `{column}` | Full dataset | Dev subset |", "|---|---|---|"]
    for value, n in full.most_common():
        lines.append(
            f"| {value} | {n:,} ({100 * n / len(households):.1f}%) | "
            f"{part[value]:,} ({100 * part[value] / len(subset):.1f}%) |"
        )
    return lines


def build_doc(households: list[dict], blocks: list[str], min_share: float, min_households: int) -> str:
    subset = [h for h in households if h["file"] in set(blocks)]
    rows = []
    for b in blocks:
        hs = [h for h in households if h["file"] == b]
        groups = ", ".join(sorted({h["Acorn_grouped"] for h in hs}))
        tariffs = Counter(h["stdorToU"] for h in hs)
        rows.append(f"| `{b}` | {len(hs)} | {groups} | {tariffs.get('Std', 0)} | {tariffs.get('ToU', 0)} |")
    small = sorted(
        g for g, n in Counter(h["Acorn_grouped"] for h in households).items() if n / len(households) < min_share
    )
    lines = [
        "# Development subset",
        "",
        "US-03 (KAN-77), T-03.3 (KAN-87). Generated by `python dev_subset.py` from "
        "`informations_households.csv`.",
        "",
        "## Why complete blocks",
        "",
        "The half-hourly readings (F1) are split into 112 block files and Kaggle groups households "
        "into blocks by ACORN group and tariff. Taking the first 200 households in alphabetical order "
        "touches most of the blocks, so a developer would still read almost the whole 7.5 GB dataset.",
        "",
        "The development subset is a small set of **complete blocks**. Loading it means reading only "
        "those files, and every household in them has its full history.",
        "",
        "## How the blocks are chosen",
        "",
        "1. Blocks are added one at a time. Each step takes the block that keeps the subset closest to "
        "the full dataset's shares of ACORN group (`Acorn_grouped`) and tariff (`stdorToU`), measured as "
        f"the sum of absolute differences. Ties go to the block closest to {TARGET_PER_BLOCK} households, "
        "then the lowest block number.",
        f"2. It stops when the subset has at least {min_households} households and every ACORN group with "
        f"at least {min_share:.0%} of the households and both tariffs (`Std` and `ToU`) are present. "
        "If a group or tariff is still missing, the next block must add it.",
        "",
        "The result is deterministic: the same households file always gives the same blocks.",
        "",
    ]
    if small:
        lines += [
            f"Groups below {min_share:.0%} are not forced into the subset: {', '.join(f'`{g}`' for g in small)}.",
            "",
        ]
    lines += [
        "## Chosen blocks",
        "",
        f"**{len(blocks)} blocks, {len(subset):,} households** "
        f"({100 * len(subset) / len(households):.1f}% of {len(households):,}). "
        f"Stored in `{DEV_SUBSET_FILE.as_posix()}`.",
        "",
        "| Block | Households | ACORN groups | Std | ToU |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "## Representativeness",
        "",
        *share_table(households, subset, "Acorn_grouped"),
        "",
        *share_table(households, subset, "stdorToU"),
        "",
        "## How to use it",
        "",
        "```bash",
        "python profile_dataset.py --dev      # profile only the subset -> docs/data/profile-dev.md",
        "```",
        "",
        "In Spark code, read only the subset files:",
        "",
        "```python",
        "from dev_subset import load_dev_blocks, select_files",
        "",
        "paths = select_files(all_block_paths, load_dev_blocks())",
        "df = spark.read.csv([str(p) for p in paths], header=True, schema=F1_SCHEMA)",
        "```",
        "",
        "To change the rule, edit `dev_subset.py` and run `python dev_subset.py` again; commit the new "
        "`dev_subset.json` and this page together.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Choose the F1 development subset")
    parser.add_argument("--raw-dir", type=Path, default=Path("data/raw"))
    parser.add_argument("--min-share", type=float, default=MIN_SHARE)
    parser.add_argument("--min-households", type=int, default=MIN_HOUSEHOLDS)
    args = parser.parse_args()

    found = sorted(args.raw_dir.rglob("informations_households.csv"))
    if not found:
        raise FileNotFoundError(f"informations_households.csv not found under {args.raw_dir.resolve()}")
    households = read_households(found[0])

    blocks = choose_blocks(households, args.min_share, args.min_households)
    subset_size = sum(1 for h in households if h["file"] in set(blocks))

    DEV_SUBSET_FILE.parent.mkdir(parents=True, exist_ok=True)
    DEV_SUBSET_FILE.write_text(
        json.dumps(
            {"blocks": blocks, "households": subset_size, "min_share": args.min_share,
             "min_households": args.min_households},
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )
    DOC_FILE.parent.mkdir(parents=True, exist_ok=True)
    DOC_FILE.write_text(build_doc(households, blocks, args.min_share, args.min_households), encoding="utf-8")

    print(f"Dev subset: {len(blocks)} blocks, {subset_size} households -> {', '.join(blocks)}")
    print(f"Written {DEV_SUBSET_FILE} and {DOC_FILE}")


if __name__ == "__main__":
    main()